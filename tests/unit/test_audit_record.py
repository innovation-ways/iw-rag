    def test_raw_pii_values_absent_from_extracted_metadata(self) -> None:
        """PII discipline: raw email/phone values are NOT present in extracted metadata."""
        import json

        from iw_rag.guardrails.audit import _extract_redaction_metadata

        raw_email = "alice@example.com"
        raw_phone = "555-867-5309"

        v = Verdict(
            kind="sanitize",
            value="redact",
            # The reason encodes type+count only — never the raw value.
            reason="pii_redacted:EMAIL_ADDRESS,1",
        )
        result = _extract_redaction_metadata({}, [v])
        blob = json.dumps(result)
        assert raw_email not in blob, "Raw email must not appear in redaction metadata"
