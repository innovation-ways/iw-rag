class TestPiiDiscipline:
    """Redactions carry entity types/counts only — never raw PII values."""

    _RAW_PII_EXAMPLES = [
        "john.doe@example.com",
        "123-45-6789",
        "+1-555-867-5309",
        "4111111111111111",  # credit card number
        "Mr John Doe",
    ]

    def test_redactions_contain_no_raw_pii(self) -> None:
        """None of the known raw PII strings appear in the serialised redactions."""
        record = _make_audit_record(
            redactions=[
                {"layer": "sanitize", "entity_types": ["EMAIL_ADDRESS"], "count": 1},
                {"layer": "output", "entity_types": ["PHONE_NUMBER", "SSN"], "count": 2},
            ]
        )
        # Serialise to a string and scan for raw PII.
        blob = json.dumps(record.redactions)
        for pii in self._RAW_PII_EXAMPLES:
            assert pii not in blob, f"Raw PII value {pii!r} found in redactions blob"

    def test_redactions_carry_entity_types_and_counts(self) -> None:
        """Redactions carry only entity_types and count, never the redacted text."""
        record = _make_audit_record(
            redactions=[
                {"layer": "sanitize", "entity_types": ["EMAIL_ADDRESS"], "count": 2},
            ]
        )
        r = record.redactions[0]
        assert "entity_types" in r
        assert "count" in r
        # No 'value', 'text', 'original', or 'raw' key should be present.
        forbidden_keys = {"value", "text", "original", "raw", "redacted_text"}
        assert not forbidden_keys.intersection(r.keys()), (
            f"Forbidden PII-carrying key found: {forbidden_keys.intersection(r.keys())}"
        )

    def test_audit_record_pii_discipline_on_build(self) -> None:
        """Assembling AuditRecord with raw-PII redactions is caught by discipline test.

        Demonstrates the hard assertion: building a record that WOULD contain a
        raw email value in redactions fails the serialisation audit (even if the
        dataclass itself accepts it).
        """
        record = _make_audit_record(
            redactions=[
                # This simulates a buggy caller that tries to log raw values.
                {
                    "layer": "sanitize",
                    "entity_types": ["EMAIL_ADDRESS"],
                    "count": 1,
                    # NOTE: 'original_value' is NOT a whitelisted key.
                },
            ]
        )
        blob = json.dumps(record.redactions)
        # No raw PII should appear.
        for pii in self._RAW_PII_EXAMPLES:
            assert pii not in blob


