class TestAuditRecordShape:
    """AuditRecord is a frozen dataclass with the spec-mandated fields."""

    def test_fields_match_spec(self) -> None:
        """All spec-required fields are present on AuditRecord instances."""
        record = _make_audit_record()
        assert record.request_id == "req-unit-test-001"
        assert record.principal == "u1"
        assert record.query == "What is the Q3 invoice total?"
        assert record.acl_filter == ["finance", "all-staff"]
        assert record.retrieved_chunk_ids == ["chunk-a", "chunk-b"]
        assert len(record.guard_verdicts) == 2
        assert len(record.redactions) == 1
        assert record.disposition == "answered"
        assert record.timestamp

    def test_is_frozen(self) -> None:
        """AuditRecord is a frozen dataclass — mutation raises."""
        record = _make_audit_record()
        with pytest.raises(
            (dataclasses.FrozenInstanceError, AttributeError), match="cannot assign"
        ):
            record.query = "mutated"  # type: ignore[misc]

    def test_disposition_literals(self) -> None:
        """All three disposition values are accepted."""

        for disp in ("answered", "refused", "rejected"):
            r = _make_audit_record(disposition=disp)
            assert r.disposition == disp

    def test_round_trip_to_row_shape(self) -> None:
        """The record converts to a dict matching the DB row shape."""
        record = _make_audit_record()
        row = dataclasses.asdict(record)
        assert "id" not in row  # id is generated by Postgres
        assert row["request_id"] == record.request_id
        assert row["principal"] == record.principal
        assert row["query"] == record.query
        assert row["acl_filter"] == record.acl_filter
        assert row["retrieved_chunk_ids"] == record.retrieved_chunk_ids
        assert row["disposition"] == record.disposition
        assert row["timestamp"] == record.timestamp


