class TestGuardVerdictsSerialization:
    """guard_verdicts serialise to a JSON-able list (jsonb-ready)."""

    def test_guard_verdicts_json_serializable(self) -> None:
        """guard_verdicts can be dumped to JSON (jsonb-compatible)."""
        record = _make_audit_record()
        # Serialize the guard verdicts to JSON as the repository will.
        from iw_rag.guardrails.audit import _serialize_guard_verdicts

        serialized = _serialize_guard_verdicts(record.guard_verdicts)
        # Must be a list of dicts.
        assert isinstance(serialized, list)
