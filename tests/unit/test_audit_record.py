class TestAssembleFromState:
    """audit_node assembles AuditRecord from GraphState correctly."""

    def test_uses_original_question_not_rewrite(self) -> None:
        """query picks original_question, not the possibly rewritten question."""
        from iw_rag.guardrails.audit import assemble_audit_record

        state: GraphState = {
            "question": "REWRITTEN: quarterly financials",  # type: ignore[typeddict-item]
            "original_question": "What is the Q3 invoice total?",
            "access_context": _CTX,
            "verdicts": [
                Verdict(kind="router", value="retrieve", reason=""),
                Verdict(kind="grade_documents", value="correct", reason=""),
            ],
            "graded": [],
            "disposition": "answered",  # type: ignore[typeddict-item]
            "diagnostics": {},
        }
        record = assemble_audit_record(state, disposition="answered")
        # MUST use original_question, not the rewritten one.
        assert record.query == "What is the Q3 invoice total?"
        assert "REWRITTEN" not in record.query

    def test_picks_full_verdicts_trail(self) -> None:
        """All verdicts in the trail are captured in guard_verdicts."""
