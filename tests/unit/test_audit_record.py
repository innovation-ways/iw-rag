        record = assemble_audit_record(state, disposition="answered")
        # All three verdicts are represented.
        assert len(record.guard_verdicts) == 3
        kinds = [gv.layer for gv in record.guard_verdicts]
        assert "router" in kinds
        assert "input_guard" in kinds
        assert "grade_generation" in kinds

