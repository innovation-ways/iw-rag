def _make_guard_verdict(
    layer: str = "input",
    decision: str = "allow",
    score: float = 0.1,
    reason: str = "clean",
) -> GuardVerdict:
    """Create a minimal GuardVerdict for testing.

    Args:
        layer: Guard layer label.
        decision: allow/block/redact/flag.
        score: Numeric confidence.
        reason: Human-readable reason.

    Returns:
        A frozen ``GuardVerdict`` instance.
    """
    return GuardVerdict(layer=layer, decision=decision, score=score, reason=reason)  # type: ignore[arg-type]


def _make_audit_record(**overrides: Any) -> AuditRecord:  # noqa: F821
    """Create a minimal AuditRecord for testing.

    Args:
        **overrides: Field values to override in the default AuditRecord.

    Returns:
        A frozen ``AuditRecord`` instance.
    """
    from iw_rag.guardrails.audit import AuditRecord

    defaults: dict[str, Any] = {
        "request_id": "req-unit-test-001",
        "principal": "u1",
        "query": "What is the Q3 invoice total?",
        "acl_filter": ["finance", "all-staff"],
        "retrieved_chunk_ids": ["chunk-a", "chunk-b"],
        "guard_verdicts": [
            _make_guard_verdict(layer="input", decision="allow", score=0.1),
            _make_guard_verdict(layer="output", decision="allow", score=0.05),
        ],
        "redactions": [{"layer": "sanitize", "entity_types": ["EMAIL_ADDRESS"], "count": 1}],
        "disposition": "answered",
        "timestamp": datetime.now(UTC).isoformat(),
    }
    defaults.update(overrides)
    return AuditRecord(**defaults)


